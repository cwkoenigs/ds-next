"""Hidden acceptance tests for the `envmerge` console script."""

import os
import re
import subprocess

import pytest

NAME_LINE = re.compile(r'^([A-Za-z_][A-Za-z0-9_]*)="(.*)"$')
ESCAPES = {"n": "\n", "t": "\t", "\\": "\\", '"': '"', "$": "$"}

BASIC_SCHEMA = """
[vars.HOST]
type = "string"
required = true

[vars.PORT]
type = "port"
default = "8080"

[vars.DEBUG]
type = "bool"
default = "false"

[vars.MODE]
type = "enum"
values = ["dev", "prod"]
"""

STRING_X_SCHEMA = """
[vars.X]
type = "string"
"""


# ---------------------------------------------------------------- helpers


def run(cwd, *args):
    return subprocess.run(
        [os.environ["TARGET_BIN"], *map(str, args)],
        cwd=cwd,
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
        timeout=60,
    )


def write(path, content):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")
    return path


def merge(tmp_path, schema, envs, extra=(), out="out.env"):
    """envs: list of (filename, content). Runs with cwd=tmp_path."""
    write(tmp_path / "schema.toml", schema)
    for name, content in envs:
        write(tmp_path / name, content)
    names = [name for name, _ in envs]
    return run(tmp_path, "schema.toml", "--out", out, *names, *extra)


def combined(p):
    return p.stdout + "\n" + p.stderr


def report_lines(p):
    return [
        line
        for line in combined(p).splitlines()
        if line.startswith("ERROR ") or line.startswith("WARN ")
    ]


def has_error_for(p, name):
    return any(line.startswith(f"ERROR {name}:") for line in report_lines(p))


def no_traceback(p):
    return "Traceback" not in combined(p)


def decode(inner):
    res = []
    i = 0
    while i < len(inner):
        c = inner[i]
        if c == "\\":
            assert i + 1 < len(inner), f"dangling backslash in {inner!r}"
            nxt = inner[i + 1]
            assert nxt in ESCAPES, f"unknown escape \\{nxt} in {inner!r}"
            res.append(ESCAPES[nxt])
            i += 2
        else:
            assert c != '"', f"unescaped quote in {inner!r}"
            res.append(c)
            i += 1
    return "".join(res)


def read_out(path):
    """Return (header, [(name, decoded value), ...]) of a generated file."""
    text = path.read_text(encoding="utf-8")
    lines = text.split("\n")
    if lines and lines[-1] == "":
        lines.pop()
    assert lines, "output file is empty"
    header, body = lines[0], lines[1:]
    pairs = []
    for line in body:
        m = NAME_LINE.match(line)
        assert m, f"bad output line {line!r}"
        pairs.append((m.group(1), decode(m.group(2))))
    return header, pairs


def out_dict(path):
    return dict(read_out(path)[1])


def assert_merged(p, n_vars, n_files):
    assert re.search(
        rf"^MERGED {n_vars} from {n_files} files?$", combined(p), re.M
    ), combined(p)


