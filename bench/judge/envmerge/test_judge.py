SPECIAL_ENV = "\n".join(
    [
        r'NL="line1\nline2"',
        r"""SQ='back\slash "quoted" $HOME'""",
        r'TAB="tab\there"',
        "PLAIN=plain",
        r'UNI="ünï ✓ \$x"',
        r'DQ="\\\""',
    ]
) + "\n"

SPECIAL_EXPECTED = {
    "NL": "line1\nline2",
    "SQ": 'back\\slash "quoted" $HOME',
    "TAB": "tab\there",
    "PLAIN": "plain",
    "UNI": "ünï ✓ $x",
    "DQ": '\\"',
}


def special_schema():
    return "".join(f'[vars.{n}]\ntype = "string"\n\n' for n in SPECIAL_EXPECTED)


def test_output_values_escaped_one_line_each(tmp_path):
    p = merge(tmp_path, special_schema(), [("base.env", SPECIAL_ENV)])
    assert p.returncode == 0, combined(p)
    text = (tmp_path / "out.env").read_text(encoding="utf-8")
    body = [line for line in text.split("\n")[1:] if line != ""]
    assert len(body) == len(SPECIAL_EXPECTED)
    assert "\t" not in text
    assert out_dict(tmp_path / "out.env") == SPECIAL_EXPECTED
    assert_merged(p, len(SPECIAL_EXPECTED), 1)


def test_output_round_trips_through_envmerge(tmp_path):
    p = merge(tmp_path, special_schema(), [("base.env", SPECIAL_ENV)])
    assert p.returncode == 0, combined(p)
    p2 = run(tmp_path, "schema.toml", "--out", "again.env", "out.env")
    assert p2.returncode == 0, combined(p2)
    first = (tmp_path / "out.env").read_text(encoding="utf-8").split("\n")[1:]
    second = (tmp_path / "again.env").read_text(encoding="utf-8").split("\n")[1:]
    assert first == second


