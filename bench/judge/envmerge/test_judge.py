def test_basic_merge_writes_sorted_quoted_output(tmp_path):
    p = merge(
        tmp_path,
        BASIC_SCHEMA,
        [("base.env", "HOST=example.org\nPORT=1000\n"), ("over.env", "PORT=2000\n")],
    )
    assert p.returncode == 0, combined(p)
    header, pairs = read_out(tmp_path / "out.env")
    assert re.fullmatch(r"# generated by envmerge from base\.env, ?over\.env", header)
    assert pairs == [("DEBUG", "false"), ("HOST", "example.org"), ("PORT", "2000")]
    assert_merged(p, 3, 2)
    assert not any(line.startswith("ERROR") for line in report_lines(p))


